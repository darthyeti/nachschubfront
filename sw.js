// Service worker: after one visit the game starts without a network.
//
// A classic worker, not a module, because iPadOS only learned module workers
// late and this has to run on the device the game is aimed at.
//
// The block below is written by `npm run precache` when the game is published
// (the Pages workflow runs it on every copy it deploys). In the repository it is
// a placeholder: no build, no files, and then this worker caches nothing and
// answers no request, so a developer always sees the files on disk. A unit test
// checks the generator and that the placeholder is what gets committed.

// --- generated by npm run precache, do not edit ---
const VERSION = 'dev';
const BUILD = '';
const PRECACHE = [

];
// --- end generated ---

/**
 * One cache per build. The hash covers the contents of every precached file, so
 * any change gives the new worker a cache of its own and the old one is thrown
 * away on activate. Nothing is ever served from a previous build's cache.
 */
const CACHE = `nachschubfront-${VERSION}-${BUILD}`;

/** False for the placeholder the repository carries: a pass-through worker. */
const PUBLISHED = BUILD !== '';

self.addEventListener('install', (event) => {
  // No skipWaiting: a running match must not be pulled out from under the
  // player. The new worker waits until the page asks for it (see 'message').
  if (!PUBLISHED) return;
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const name of await caches.keys()) {
        if (name !== CACHE && name.startsWith('nachschubfront-')) await caches.delete(name);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  // A development worker leaves every request to the network.
  if (!PUBLISHED) return;
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Any navigation lands on the one page the game has. That also covers a deep
  // link with a seed in the query, which is not a cache entry of its own.
  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const cached = await caches.match('./index.html', { cacheName: CACHE });
        if (cached) return cached;
        return fetch(request);
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { cacheName: CACHE, ignoreSearch: true });
      if (cached) return cached;
      // Not in the build: fetch it and keep it, so a file added later is
      // available offline from its second use on.
      try {
        const response = await fetch(request);
        if (response.ok && response.type === 'basic') {
          const cache = await caches.open(CACHE);
          cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        // Offline and nothing cached: let the page deal with it.
        throw error;
      }
    })(),
  );
});

self.addEventListener('message', (event) => {
  // The page asks for the update once the player has said yes to it.
  if (event.data && event.data.type === 'skipWaiting') self.skipWaiting();
});
