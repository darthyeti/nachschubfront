// Writes the generated block in sw.js: version, build hash and the list of
// files the game is made of.
//
// Run it after anything the browser loads has changed — `npm run precache`. The
// unit test in tests/unit/precache.test.js fails until you do, because a stale
// list is a cache that never updates.

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT, collectPrecache, precacheHash } from './precache-list.mjs';
import { APP_VERSION } from '../../src/data/version.js';

const START = '// --- generated by npm run precache, do not edit ---';
const END = '// --- end generated ---';

/** The generated block as it has to stand in sw.js. */
export function precacheBlock(files, hash, version = APP_VERSION) {
  const list = files.map((file) => `  '${file}',`).join('\n');
  return [START, `const VERSION = '${version}';`, `const BUILD = '${hash}';`, `const PRECACHE = [`, list, `];`, END].join(
    '\n',
  );
}

/** Replaces the block in the given worker source. */
export function withBlock(source, block) {
  const from = source.indexOf(START);
  const to = source.indexOf(END);
  if (from === -1 || to === -1) throw new Error('sw.js has lost its generated block');
  return source.slice(0, from) + block + source.slice(to + END.length);
}

export async function buildWorker(root = ROOT) {
  const files = await collectPrecache(root);
  const hash = await precacheHash(files, root);
  const path = join(root, 'sw.js');
  const source = await readFile(path, 'utf8');
  return { path, files, hash, next: withBlock(source, precacheBlock(files, hash)), current: source };
}

// Only when run directly, so the test can import the helpers above.
if (import.meta.url === `file://${process.argv[1]}`) {
  const { path, files, hash, next, current } = await buildWorker();
  if (next === current) {
    console.log(`sw.js is up to date (${files.length} files, build ${hash}).`);
  } else {
    await writeFile(path, next);
    console.log(`sw.js written: ${files.length} files, version ${APP_VERSION}, build ${hash}.`);
  }
}
