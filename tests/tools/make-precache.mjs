// Writes the generated block in sw.js: version, build hash and the list of
// files the game is made of.
//
// The repository carries sw.js with a placeholder block (empty build, no files),
// which makes the worker a pass-through during development. The block is filled
// when the game is published: the Pages workflow runs this on every copy it
// deploys (`node tests/tools/make-precache.mjs --root <copy>`). A plain
// `npm run precache` fills the block in the working tree, for trying the
// offline behaviour by hand; `--placeholder` puts the placeholder back. The
// unit test in tests/unit/precache.test.js checks the generator and that the
// repository still holds the placeholder.

import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { ROOT, collectPrecache, precacheHash } from './precache-list.mjs';

const START = '// --- generated by npm run precache, do not edit ---';
const END = '// --- end generated ---';

/** What the repository holds: no build, no files, the worker stays out of the way. */
export const PLACEHOLDER_VERSION = 'dev';

/** The generated block as it has to stand in sw.js. */
export function precacheBlock(files, hash, version) {
  const list = files.map((file) => `  '${file}',`).join('\n');
  return [START, `const VERSION = '${version}';`, `const BUILD = '${hash}';`, `const PRECACHE = [`, list, `];`, END].join(
    '\n',
  );
}

/** The block the repository carries between releases. */
export function placeholderBlock() {
  return precacheBlock([], '', PLACEHOLDER_VERSION);
}

/** Replaces the block in the given worker source. */
export function withBlock(source, block) {
  const from = source.indexOf(START);
  const to = source.indexOf(END);
  if (from === -1 || to === -1) throw new Error('sw.js has lost its generated block');
  return source.slice(0, from) + block + source.slice(to + END.length);
}

/**
 * The version number of the tree being built, read from the file rather than
 * imported: the tree may be a copy of another commit than the one this tool
 * runs from (a pull request preview), and its code must not run here.
 */
export async function readVersion(root = ROOT) {
  const source = await readFile(join(root, 'src', 'data', 'version.js'), 'utf8');
  const match = source.match(/APP_VERSION\s*=\s*'([^']+)'/);
  if (!match) throw new Error('src/data/version.js does not declare APP_VERSION');
  return match[1];
}

/**
 * The worker as it has to be published for the tree under `root`.
 * @returns {Promise<{path: string, files: string[], hash: string, version: string, next: string, current: string}>}
 */
export async function buildWorker(root = ROOT) {
  const files = await collectPrecache(root);
  const hash = await precacheHash(files, root);
  const version = await readVersion(root);
  const path = join(root, 'sw.js');
  const source = await readFile(path, 'utf8');
  return { path, files, hash, version, next: withBlock(source, precacheBlock(files, hash, version)), current: source };
}

/** Puts the placeholder back into the worker under `root`. */
export async function resetWorker(root = ROOT) {
  const path = join(root, 'sw.js');
  const source = await readFile(path, 'utf8');
  return { path, next: withBlock(source, placeholderBlock()), current: source };
}

// Only when run directly, so the test can import the helpers above.
if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const at = args.indexOf('--root');
  const root = at >= 0 ? resolve(process.cwd(), args[at + 1]) : ROOT;
  if (args.includes('--placeholder')) {
    const { path, next, current } = await resetWorker(root);
    if (next !== current) await writeFile(path, next);
    console.log(`sw.js carries the placeholder block again.`);
  } else {
    const { path, files, hash, version, next, current } = await buildWorker(root);
    if (next === current) {
      console.log(`sw.js is up to date (${files.length} files, version ${version}, build ${hash}).`);
    } else {
      await writeFile(path, next);
      console.log(`sw.js written: ${files.length} files, version ${version}, build ${hash}.`);
    }
    if (root === ROOT) {
      console.log('This is a build block for trying things out. Do not commit it; `npm run precache -- --placeholder` puts the placeholder back.');
    }
  }
}
