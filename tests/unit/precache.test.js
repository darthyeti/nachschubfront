// The service worker's file list. The repository carries sw.js with a
// placeholder block; the list is generated when the game is published. A wrong
// list means the game keeps starting from an old cache, so this test guards the
// generator, and that nobody commits a build block by accident.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { promisify } from 'node:util';

import { ROOT, collectPrecache, precacheHash } from '../tools/precache-list.mjs';
import { PLACEHOLDER_VERSION, buildWorker, placeholderBlock, readVersion, resetWorker } from '../tools/make-precache.mjs';
import { APP_VERSION } from '../../src/data/version.js';

const worker = await readFile(join(ROOT, 'sw.js'), 'utf8');
const GENERATOR = join(ROOT, 'tests', 'tools', 'make-precache.mjs');

test('the repository holds the placeholder, not a build', async () => {
  const { next } = await resetWorker();
  assert.equal(worker, next, 'sw.js carries a build block — run: npm run precache -- --placeholder');
  assert.match(worker, /const VERSION = 'dev';/);
  assert.match(worker, /const BUILD = '';/);
  assert.equal(PLACEHOLDER_VERSION, 'dev');
  assert.ok(worker.includes(placeholderBlock()));
});

test('the placeholder worker stays out of the way', () => {
  // Without a build it neither fills a cache nor answers a request, so a
  // developer always sees the files on disk.
  assert.match(worker, /const PUBLISHED = BUILD !== '';/);
  const install = worker.slice(worker.indexOf("addEventListener('install'"), worker.indexOf("addEventListener('activate'"));
  const fetch = worker.slice(worker.indexOf("addEventListener('fetch'"), worker.indexOf("addEventListener('message'"));
  assert.match(install, /if \(!PUBLISHED\) return;/, 'install must not precache without a build');
  assert.match(fetch, /if \(!PUBLISHED\) return;/, 'fetch must go to the network without a build');
});

test('the generator fills the block with version, hash and every file', async () => {
  const { next, files, hash, version } = await buildWorker();
  assert.equal(version, APP_VERSION);
  assert.match(next, new RegExp(`const VERSION = '${APP_VERSION.replace(/\./g, '\\.')}';`));
  assert.match(next, new RegExp(`const BUILD = '${hash}';`));
  assert.match(hash, /^[0-9a-f]{12}$/);
  assert.match(next, /const CACHE = `nachschubfront-\$\{VERSION\}-\$\{BUILD\}`;/);
  for (const file of files) assert.ok(next.includes(`  '${file}',`), `${file} is not in the generated list`);
  // The block is replaced in place; the markers survive for the next run.
  assert.ok(next.includes('// --- generated by npm run precache, do not edit ---'));
  assert.ok(next.includes('// --- end generated ---'));
  // And the placeholder can be put back from a build.
  const { withBlock } = await import('../tools/make-precache.mjs');
  assert.equal(withBlock(next, placeholderBlock()), worker);
});

test('the list holds everything the game loads and nothing it does not', async () => {
  const files = await collectPrecache();
  assert.ok(files.includes('./index.html'));
  assert.ok(files.includes('./manifest.webmanifest'));
  assert.ok(files.includes('./src/main.js'));
  assert.ok(files.includes('./src/ui/style.css'));
  assert.ok(files.some((f) => f.endsWith('.woff2')), 'the fonts have to work offline too');
  assert.ok(files.some((f) => f.startsWith('./assets/icons/')), 'the icons belong to the installed app');

  for (const file of files) {
    assert.ok(file.startsWith('./'), `${file} is not relative to the page`);
    assert.ok(!file.includes('/tests/'), `${file} is a development file`);
    assert.ok(!file.includes('/docs/') && !file.includes('/reference/'), `${file} is not served`);
    assert.ok(!file.includes('node_modules'), `${file} would break the no-dependency rule`);
  }
});

test('every module main.js reaches is in the list', async () => {
  // Walks the real import graph, so a module added without being listed fails
  // here rather than the first time somebody plays offline.
  const files = new Set(await collectPrecache());
  const seen = new Set();
  const queue = ['./src/main.js'];
  while (queue.length > 0) {
    const path = queue.pop();
    if (seen.has(path)) continue;
    seen.add(path);
    assert.ok(files.has(path), `${path} is missing from the precache list`);
    const source = await readFile(join(ROOT, path.slice(2)), 'utf8');
    for (const match of source.matchAll(/^\s*(?:import|export)[^'"]*from\s*['"]([^'"]+)['"]/gm)) {
      const target = match[1];
      if (!target.startsWith('.')) continue;
      const dir = path.slice(2).split('/').slice(0, -1).join('/');
      queue.push(`./${new URL(target, `file:///${dir}/`).pathname.slice(1)}`);
    }
  }
  assert.ok(seen.size > 40, `only ${seen.size} modules were walked`);
});

test('the build hash follows both the names and the contents', async (t) => {
  const files = await collectPrecache();
  const full = await precacheHash(files);
  assert.notEqual(full, await precacheHash(files.slice(0, -1)), 'a dropped file changes the hash');

  // Contents, on a throwaway tree: the same file name with one byte changed has
  // to give a different cache name, or an update would be served from the old cache.
  const dir = await mkdtemp(join(tmpdir(), 'precache-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  await writeFile(join(dir, 'a.js'), 'export const x = 1;');
  const one = await precacheHash(['./a.js'], dir);
  await writeFile(join(dir, 'a.js'), 'export const x = 2;');
  assert.notEqual(one, await precacheHash(['./a.js'], dir));
});

test('the generator builds another tree with that tree\'s version', async (t) => {
  // The Pages workflow runs the generator from main against a copy of a pull
  // request. The copy's own version has to end up in the cache name, and none
  // of the copy's code may run for that.
  const dir = await mkdtemp(join(tmpdir(), 'precache-root-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  for (const sub of ['src/data', 'assets/fonts', 'assets/icons']) await mkdir(join(dir, sub), { recursive: true });
  await writeFile(join(dir, 'index.html'), '<!doctype html>');
  await writeFile(join(dir, 'manifest.webmanifest'), '{}');
  await writeFile(join(dir, 'src', 'main.js'), 'throw new Error("must not be imported");');
  await writeFile(join(dir, 'src', 'data', 'version.js'), "export const APP_VERSION = '9.9.9';\nthrow new Error('must not be imported');\n");
  await writeFile(join(dir, 'sw.js'), worker);

  assert.equal(await readVersion(dir), '9.9.9');
  const { next, files, version } = await buildWorker(dir);
  assert.equal(version, '9.9.9');
  assert.deepEqual(files, ['./index.html', './manifest.webmanifest', './src/data/version.js', './src/main.js']);
  assert.match(next, /const VERSION = '9\.9\.9';/);

  // The command line the workflow uses, relative to the working directory.
  const run = promisify(execFile);
  const { stdout } = await run(process.execPath, [GENERATOR, '--root', '.'], { cwd: dir });
  assert.match(stdout, /sw\.js written: 4 files, version 9\.9\.9, build [0-9a-f]{12}\./);
  assert.equal(await readFile(join(dir, 'sw.js'), 'utf8'), next);
  const again = await run(process.execPath, [GENERATOR, '--root', '.'], { cwd: dir });
  assert.match(again.stdout, /sw\.js is up to date/);
  await run(process.execPath, [GENERATOR, '--root', '.', '--placeholder'], { cwd: dir });
  assert.equal(await readFile(join(dir, 'sw.js'), 'utf8'), worker);
});

test('the worker waits instead of reloading a running match', () => {
  // skipWaiting is called in exactly one place, and that place is the message
  // handler the page uses once the player has said yes.
  const calls = worker.match(/self\.skipWaiting\(\)/g) ?? [];
  assert.equal(calls.length, 1, 'skipWaiting belongs in one handler only');
  const install = worker.slice(worker.indexOf("addEventListener('install'"), worker.indexOf("addEventListener('activate'"));
  assert.ok(!install.includes('self.skipWaiting()'), 'install must not take over a running page');
  assert.match(worker, /event\.data\.type === 'skipWaiting'/, 'the page asks for the update');
  assert.match(worker, /caches\.delete\(name\)/, 'old caches go on activate');
});
